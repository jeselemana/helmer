/**
 * Extracts the normalized lowercase domain from an email address.
 * @param {string} email
 * @returns {string}
 */
export function extractEmailDomain(email) {
  const raw = String(email || "").trim().toLowerCase();
  const atIndex = raw.lastIndexOf("@");
  if (atIndex <= 0 || atIndex === raw.length - 1) return "";
  return raw.slice(atIndex + 1).replace(/\.+$/, "");
}

/**
 * Returns true if the email address belongs to a known disposable email domain
 * or a subdomain of one.
 * @param {string} email
 * @returns {boolean}
 */
export function isDisposableEmail(email) {
  const domain = extractEmailDomain(email);
  if (!domain) return false;
  if (DISPOSABLE_EMAIL_DOMAINS.has(domain)) return true;

  const labels = domain.split(".");
  for (let i = 1; i <= labels.length - 2; i += 1) {
    const parent = labels.slice(i).join(".");
    if (DISPOSABLE_EMAIL_DOMAINS.has(parent)) return true;
  }
  return false;
}
